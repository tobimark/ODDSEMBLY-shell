"""
Generate src/svg/icons.ts from the SVG icons extracted out of cromma-bees.exe.

The native app embeds its icon theme as literal `icons/<name>.svg` strings.
`.tmp/shell/extract_svgs3.py` dumped them into analysis/ui-shell/svgs/, one file
per icon; this script folds them into a typed TS module so the replica uses the
*exact* same vector artwork (same paths, same stroke widths, same viewBox).

usage: python tools/gen_icons.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / 'analysis' / 'ui-shell' / 'svgs'
OUT = ROOT / 'src' / 'svg' / 'icons.ts'

OUTER_ATTRS = re.compile(r'<svg\b[^>]*>', re.S)
DROP_ATTRS = re.compile(r'\s(?:width|height|style|role|fill)="[^"]*"')


def parse(text: str):
    m = OUTER_ATTRS.search(text)
    if not m:
        return None
    open_tag = m.group(0)
    vb = re.search(r'viewBox="([^"]+)"', open_tag)
    if not vb:
        return None
    inner = text[m.end():text.rindex('</svg>')]
    # the outer <svg> carries presentation attrs that must survive (fill, stroke,
    # stroke-width, stroke-linecap ...) -> keep them on our wrapper via `rootAttrs`
    attrs = DROP_ATTRS.sub('', open_tag[len('<svg'):-1]).strip()
    attrs = re.sub(r'\s*viewBox="[^"]*"', '', attrs).strip()
    attrs = re.sub(r'\s*xmlns="[^"]*"', '', attrs).strip()
    attrs = re.sub(r'\s*style="[^"]*"', '', attrs).strip()
    attrs = attrs.lstrip()
    return vb.group(1), attrs, inner.strip()


def main():
    icons = {}
    cheap = {}
    for f in sorted(SRC.glob('icons__*.svg')):
        name = f.name[len('icons__'):-len('.svg')]
        parsed = parse(f.read_text(encoding='utf-8', errors='replace'))
        if not parsed:
            print('SKIP (unparsed)', f.name)
            continue
        vb, attrs, inner = parsed
        if len(vb.split()) == 4 and vb.startswith('0 0 16 16'):
            cheap[name] = inner
        else:
            icons[name] = {'vb': vb, 'attrs': attrs, 'inner': inner}

    lines = []
    lines.append('/**')
    lines.append(' * AUTO-GENERATED by tools/gen_icons.py — do not edit by hand.')
    lines.append(' *')
    lines.append(' * Vector artwork lifted verbatim from the CrommaCode 0.3.11 binary, where the')
    lines.append(' * icon theme ships as literal `icons/<name>.svg` string constants.')
    lines.append(' * Paths, stroke widths and viewBoxes are identical to the shipped app.')
    lines.append(' */')
    lines.append('')
    lines.append('export type IconName =')
    for n in sorted(list(cheap) + list(icons)):
        lines.append("  | '%s'" % n)
    lines[-1] += ';'
    lines.append('')
    lines.append('/** icons drawn on the standard 16x16 grid */')
    lines.append('export const ICON_PATHS: Record<string, string> = {')
    for n, inner in sorted(cheap.items()):
        lines.append("  '%s': %s," % (n, json.dumps(inner, ensure_ascii=False)))
    lines.append('};')
    lines.append('')
    lines.append('/** icons with a non-16 viewBox: { viewBox, rootAttrs, inner } */')
    lines.append('export const ICON_SPECIAL: Record<string, { vb: string; attrs: string; inner: string }> = {')
    for n, d in sorted(icons.items()):
        lines.append("  '%s': { vb: %s, attrs: %s, inner: %s }," % (
            n, json.dumps(d['vb']), json.dumps(d['attrs'], ensure_ascii=False),
            json.dumps(d['inner'], ensure_ascii=False)))
    lines.append('};')
    lines.append('')
    lines.append('export const ICON_NAMES: string[] = [...Object.keys(ICON_PATHS), ...Object.keys(ICON_SPECIAL)];')
    lines.append('')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'wrote {OUT}  ({len(cheap)} icons @16, {len(icons)} special)')


if __name__ == '__main__':
    main()
